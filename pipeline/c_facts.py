# 仕事チャンネル 型C（職業の1日「年収〇〇万円の〇〇の1日」）の facts.json を書く（手順書 §3 型C・§4）
#   python -X utf8 pipeline\c_facts.py make <作業フォルダ> <キー>      … キーは job_facts_common.JOBS のキー（truck・kango など）
# ・主役は「統計の平均から作った、平均的な〇〇さん」。年齢・勤続年数・年収・労働時間は、その職業の統計の平均（賃金構造 職種 第1表）
# ・全国平均は賃金構造 産業大分類 第1表の産業計（同じ範囲：一般労働者・民営・10人以上）
# ・C-3（新人とベテラン）の年収は、賃金構造 職種 第5表の年齢別の値
# ・C-2（給料日までの1か月）は手取りの計算（pipeline\tedori.py・data\tedori_<年度>.json）がまだ無いので使えない
# ・1日の時刻（朝〇時〜夜〇時）は、この統計に無い。facts.json に「出典なし」と書く
import sys
import job_facts_common as c

YOUNG = "20～24歳"
VETS = ["50～54歳", "55～59歳"]  # 「50代」。山場は 50～54歳、55～59歳 は並べて見せる用
# ネタ帳の題と統計の職種のずれ（題が職種の一部だけを指す時）
NARROW = {"truck": "題の「長距離」は統計で分けられない。値は営業用大型貨物自動車運転者の全体（長距離・近距離を合わせた平均）",
          "kango": "題の「夜勤」は統計で分けられない。値は看護師の全体（夜勤のある人・ない人を合わせた平均）。夜勤の回数・時間の値は持っていない"}


def make(work, key):
    j = c.job(key)
    a = c.load("a1c_r7.json")
    sh = c.load("shokushu_r7.json")["data"]["男女計"]
    m40 = c.load("main40_r7.json")["data"]
    sg = a["data"]["産業別_平均"]
    official, disp = j["職種"][0], j["表示名"]
    me = c.job_row(sh, m40, official, disp)
    avg = c.avg_row(sg["産業計"], "全産業の平均（一般労働者）")
    vs = c.compare(me, avg, disp, "全産業の平均")
    dt = me["月の労働時間"] - avg["月の労働時間"]
    hero = f"統計の平均から作った、平均的な{disp}さん"

    # 年齢別（第5表）。〇〇の40年の職業か
    ages = a["data"]["職種_年齢階級"][official]["年齢階級"]
    # 値の無い年齢階級（表で「-」）は年収などを None にする
    by_age = [{"年齢階級": k, "年齢": v.get("年齢"), "勤続年数": v.get("勤続年数"), "年収_千円": v.get("年収_千円"),
               "年収_万円": c.man(v["年収_千円"]) if v.get("年収_千円") is not None else None,
               "声の年収": c.voice_man(v["年収_千円"]) if v.get("年収_千円") is not None else None,
               "月の労働時間": v.get("月の労働時間"), "時給に直した額_円": v.get("時給に直した額_円"), "労働者数_十人": v.get("労働者数")}
              for k, v in ages.items()]
    peak_age = max((r for r in by_age if r["年収_千円"] is not None), key=lambda r: r["年収_千円"])

    # C-3：20代前半と50代前半
    y, o = ages.get(YOUNG, {}), ages.get(VETS[0], {})
    c3 = None
    if y.get("年収_千円") is not None and o.get("年収_千円") is not None:
        d = o["年収_千円"] - y["年収_千円"]
        c3 = {"新人": {"年齢階級": YOUNG, "年齢": y["年齢"], "勤続年数": y["勤続年数"], "年収_万円": c.man(y["年収_千円"]),
                     "声の年収": c.voice_man(y["年収_千円"]), "月の労働時間": y["月の労働時間"], "うち残業など（超過）": y["超過実労働時間数"],
                     "時給に直した額_円": y["時給に直した額_円"], "声の時給": c.voice_yen(y["時給に直した額_円"])},
              "ベテラン": {"年齢階級": VETS[0], "年齢": o["年齢"], "勤続年数": o["勤続年数"], "年収_万円": c.man(o["年収_千円"]),
                       "声の年収": c.voice_man(o["年収_千円"]), "月の労働時間": o["月の労働時間"], "うち残業など（超過）": o["超過実労働時間数"],
                       "時給に直した額_円": o["時給に直した額_円"], "声の時給": c.voice_yen(o["時給に直した額_円"])},
              "年収の差_万円": round(d / 10, 1), "声_年収の差": f"{c.voice_man(abs(d))}{'高い' if d > 0 else '低い'}（ベテランが新人より）",
              "年収の倍率": round(o["年収_千円"] / y["年収_千円"], 2),
              "声_倍率": f"約{round(o['年収_千円'] / y['年収_千円'], 1)}倍",
              "月の労働時間の差": o["月の労働時間"] - y["月の労働時間"],
              "参考_55～59歳": {"声の年収": c.voice_man(ages[VETS[1]]["年収_千円"])} if ages.get(VETS[1], {}).get("年収_千円") is not None else None,
              "注意": "同じ人の20年後ではない（今年の20代前半と50代前半の、別の人たちの平均）。「この人も20年後にこうなる」とは言わない"}

    rs = c.load("rishoku_sangyo_r7.json")["data"]["男女計"]
    ind = None
    if j["産業"]:
        name = next(n for n, v in rs.items() if v.get("記号") == j["産業"])
        iv = c.industry_voice(name)
        sv = iv if iv.endswith("業") else iv + "業"
        ind = {"表の名前": name, "声の名前": sv, "離職率_%": rs[name]["離職率"], "全産業の離職率_%": rs["産業計"]["離職率"],
               "声_離職率": f"{disp}を含む{sv}の離職率は{rs[name]['離職率']}%", "注意": "産業の数字。職業の離職率として言わない（手順書 §3）",
               "当てはめの注意": j.get("産業の注意", "職業と産業の結びつきは、このチャンネルの当てはめ")}

    say_t = f"月の労働時間は{me['月の労働時間']}時間。全産業の平均より{abs(dt)}時間{'長い' if dt > 0 else '短い'}。" if dt else \
        f"月の労働時間は{me['月の労働時間']}時間。全産業の平均と同じ。"
    say_n = f"年収は{me['声の年収']}。全産業の平均より{vs['声_年収']}。"
    nums = [me["声の年収"], me["声の時給"], me["声の月の給与"], me["声の賞与"], avg["声の年収"], avg["声の時給"],
            f"{me['月の労働時間']}時間", f"{avg['月の労働時間']}時間", f"{abs(dt)}時間", vs["声_年収"], vs["声_時給"], vs["声_週"], vs["声_日"],
            vs["声_年収の差を月に"], f"{me['年齢']}歳", f"{me['勤続年数']}年"]
    if c3:
        nums += [c3["新人"]["声の年収"], c3["ベテラン"]["声の年収"], c3["声_年収の差"], c3["声_倍率"]]
    facts = {
        "type": "C", "frame": "C", "キー": key, "職業": disp, "職種（調査の名前）": official,
        "主役": {"呼び方": hero, "名札": hero,
               "決まり": "前置きで語り手が1回だけこの呼び方で紹介し、画面の名札にも1回出す。帯・概要欄・タイトルに断り書きは出さない（手順書 §3 型C）",
               "年齢": me["年齢"], "勤続年数": me["勤続年数"], "年収": me["声の年収"], "月の給与（きまって支給）": me["声の月の給与"],
               "年間の賞与など": me["声の賞与"], "月の労働時間": me["月の労働時間"], "うち所定内": me["うち所定内"],
               "うち残業など（超過）": me["うち残業など（超過）"], "時給に直した額": me["声の時給"],
               "家族の形": "統計に無い。その年齢の一般的な形から選ぶ（手順書 §3）。数字は付けない"},
        "定義": {"年収": "きまって支給する現金給与額×12＋年間賞与その他特別給与額", "時給に直した額": "年収÷（月の労働時間×12）",
               "月の労働時間": "所定内実労働時間数＋超過実労働時間数（1か月）", "対象": a["meta"]["賃金構造の範囲"],
               "月の給与": "きまって支給する現金給与額（残業代などを含む、税・保険料を引く前の額。手取りではない）",
               "順位": "大きい順。同じ値は同じ順位"},
        "題と統計のずれ": NARROW.get(key),
        "この職業の数字": me, "全産業の平均": avg, "比べ_全産業の平均": vs,
        "全国平均と並べる表": [
            {"物差し": "年収", disp: me["声の年収"], "全産業の平均": avg["声の年収"], "差": vs["声_年収"]},
            {"物差し": "月の労働時間", disp: f"{me['月の労働時間']}時間", "全産業の平均": f"{avg['月の労働時間']}時間",
             "差": f"{abs(dt)}時間{'長い' if dt > 0 else '短い'}" if dt else "同じ"},
            {"物差し": "時給に直した額", disp: me["声の時給"], "全産業の平均": avg["声の時給"], "差": vs["声_時給"]},
            {"物差し": "平均年齢", disp: f"{me['年齢']}歳", "全産業の平均": f"{avg['年齢']}歳"},
            {"物差し": "勤続年数", disp: f"{me['勤続年数']}年", "全産業の平均": f"{avg['勤続年数']}年"}],
        "年齢別": by_age, "年収がいちばん高い年齢階級": {"年齢階級": peak_age["年齢階級"], "声の年収": peak_age["声の年収"]},
        "〇〇の40年の職業": official in a["data"]["〇〇の40年の職業"],
        "業界": ind,
        "骨組み": {
            "C-1": {"使える": True, "注意": "時刻（朝〇時〜夜〇時）・1日の場面の長さは統計に無い。時刻は数字として言い切らず、出典の無い場面として書く"},
            "C-2": {"使える": False, "理由": "手取りの計算（pipeline\\tedori.py）と根拠表（data\\tedori_<年度>.json）がまだ無い（手順書 §3 C-2）"},
            "C-3": {"使える": c3 is not None, "値": c3}},
        "1日の時刻": {"出典": None, "注意": "賃金構造基本統計調査に始業・終業の時刻は無い。タイトルの【朝〇時〜夜〇時】の時刻は統計の値ではない"},
        "つかみ_統計の例": [say_t, say_n],
        "タイトル用": {"職業名": disp, "年収": me["声の年収"], "例": f"{disp}の1日｜年収{me['声の年収'].lstrip('約')}",
                    "時刻の注意": "【朝〇時〜夜〇時】の時刻は統計に無い（上の 1日の時刻）。入れるかはメインが決める"},
        "声で言える数字": [n for n in nums if n],
    }
    keys = ["chinkin_r7_shokushu", "chinkin_r7_shokushu_t5", "chinkin_r7_sangyo_t1"] + (["koyodoko_r7_sanko1"] if ind else [])
    facts.update(c.sources_block(keys))
    p = c.write(work, facts)
    print(f"書きました：{p}（{disp}・年収 {me['声の年収']}・月 {me['月の労働時間']}時間・C-3 {'できる' if c3 else 'できない'}）")


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 3 and args[0] == "make":
        make(args[1], args[2])
    else:
        print("使い方は先頭のコメントを見てください")
